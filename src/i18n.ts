type MessageKey = keyof typeof translations
export type Message = MessageKey | { key: MessageKey; values: Record<string, string | number> }

export class AppError extends Error {
  constructor(readonly copy: Message) {
    super(typeof copy === 'string' ? copy : copy.key)
  }
}

export function errorMessage(cause: unknown, fallback: MessageKey): Message {
  return cause instanceof AppError ? cause.copy : fallback
}

export function translate(language: Language, message: Message): string {
  const key = typeof message === 'string' ? message : message.key
  const text = translations[key][language === 'ja' ? 1 : 0]
  return typeof message === 'string'
    ? text
    : text.replace(/\{(\w+)\}/g, (placeholder, name: string) => String(message.values[name] ?? placeholder))
}
